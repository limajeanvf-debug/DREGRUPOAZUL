-- Help Desk Azul Viagens Shopping Recife — módulo integrado ao sistema principal
-- PostgreSQL 12+
-- As tabelas ficam no schema "helpdesk" para não conflitar com as do sistema principal.
-- Pode ser executado no phpPgAdmin / pgAdmin / psql ou com: npm run db:criar

CREATE SCHEMA IF NOT EXISTS helpdesk;
SET search_path TO helpdesk, public;

-- Usuários do help desk. Não há senha aqui: quem faz o login é o sistema principal.
-- id_externo = id do usuário no sistema principal (preenchido no primeiro acesso).
CREATE TABLE IF NOT EXISTS usuarios (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_externo        VARCHAR(190) UNIQUE,
  nome              VARCHAR(120) NOT NULL,
  email             VARCHAR(190) UNIQUE,
  telefone          VARCHAR(30),
  loja              VARCHAR(120),
  perfil            VARCHAR(10)  NOT NULL DEFAULT 'agente' CHECK (perfil IN ('agente','suporte','admin')),
  admin_fixo        BOOLEAN      NOT NULL DEFAULT FALSE,
  ativo             BOOLEAN      NOT NULL DEFAULT TRUE,
  criado_em         TIMESTAMPTZ(3) NOT NULL,
  atualizado_em     TIMESTAMPTZ(3) NOT NULL
);

CREATE TABLE IF NOT EXISTS lojas (
  id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome   VARCHAR(120) NOT NULL UNIQUE,
  ordem  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS categorias (
  id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome   VARCHAR(120) NOT NULL UNIQUE,
  ordem  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS configuracoes (
  chave          VARCHAR(60) PRIMARY KEY,
  valor          TEXT NOT NULL,
  atualizado_em  TIMESTAMPTZ(3) NOT NULL
);

CREATE TABLE IF NOT EXISTS chamados (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero            VARCHAR(20) UNIQUE,
  titulo            VARCHAR(160) NOT NULL,
  categoria         VARCHAR(120) NOT NULL,
  prioridade        VARCHAR(10) NOT NULL DEFAULT 'Média'
                    CHECK (prioridade IN ('Urgente','Alta','Média','Baixa')),
  status            VARCHAR(20) NOT NULL DEFAULT 'Aberto'
                    CHECK (status IN ('Aberto','Em andamento','Aguardando agente','Resolvido','Fechado')),
  loc_aereo         VARCHAR(10),
  loc_pacote        VARCHAR(40),
  descricao         TEXT NOT NULL,
  autor_id          INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  autor_nome        VARCHAR(120) NOT NULL,
  autor_email       VARCHAR(190),
  autor_loja        VARCHAR(120),
  responsavel_id    INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  responsavel_nome  VARCHAR(120),
  criado_em         TIMESTAMPTZ(3) NOT NULL,
  atualizado_em     TIMESTAMPTZ(3) NOT NULL,
  prazo_em          TIMESTAMPTZ(3) NOT NULL,
  resolvido_em      TIMESTAMPTZ(3),
  ultima_msg_visao  VARCHAR(10) CHECK (ultima_msg_visao IN ('agente','suporte')),
  ultima_msg_em     TIMESTAMPTZ(3)
);
CREATE INDEX IF NOT EXISTS ix_chamados_status     ON chamados (status);
CREATE INDEX IF NOT EXISTS ix_chamados_autor      ON chamados (autor_id);
CREATE INDEX IF NOT EXISTS ix_chamados_atualizado ON chamados (atualizado_em);

CREATE TABLE IF NOT EXISTS mensagens (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chamado_id   INTEGER NOT NULL REFERENCES chamados(id) ON DELETE CASCADE,
  autor_id     INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  autor_nome   VARCHAR(120),
  visao        VARCHAR(10) CHECK (visao IN ('agente','suporte')),
  sistema      BOOLEAN NOT NULL DEFAULT FALSE,
  texto        TEXT NOT NULL,
  qtd_anexos   INTEGER NOT NULL DEFAULT 0,
  criado_em    TIMESTAMPTZ(3) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_mensagens_chamado ON mensagens (chamado_id, criado_em);

CREATE TABLE IF NOT EXISTS anexos (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chamado_id     INTEGER NOT NULL REFERENCES chamados(id) ON DELETE CASCADE,
  mensagem_id    INTEGER REFERENCES mensagens(id) ON DELETE SET NULL,
  nome_original  VARCHAR(255) NOT NULL,
  arquivo        VARCHAR(255) NOT NULL,
  mime           VARCHAR(60)  NOT NULL,
  tamanho        INTEGER NOT NULL,
  autor_id       INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  autor_nome     VARCHAR(120),
  criado_em      TIMESTAMPTZ(3) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_anexos_chamado ON anexos (chamado_id);

CREATE TABLE IF NOT EXISTS leituras (
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  chamado_id  INTEGER NOT NULL REFERENCES chamados(id) ON DELETE CASCADE,
  visao       VARCHAR(10) NOT NULL CHECK (visao IN ('agente','suporte')),
  lido_em     TIMESTAMPTZ(3) NOT NULL,
  PRIMARY KEY (usuario_id, chamado_id, visao)
);

CREATE TABLE IF NOT EXISTS emissores (
  id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome   VARCHAR(120) NOT NULL UNIQUE,
  ordem  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS fornecedores (
  id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome   VARCHAR(120) NOT NULL UNIQUE,
  ordem  INTEGER NOT NULL DEFAULT 0
);

